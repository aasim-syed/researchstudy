#!/usr/bin/env python3
"""Regenerates the result tables in README.md and docs/technical_writeup.md from data files.

Tables live between <!-- NAME:BEGIN --> and <!-- NAME:END --> markers and are rebuilt from
  * benchmark/results/reports/*.json  (main benchmark, one quadeval report per model x method)
  * benchmark/study/*/reports/*.json  (coverage study iterations)
so no number in them is typed by hand.

    python docs/gen_tables.py
"""
import json
import os
import re
import statistics as st

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAN = json.load(open(os.path.join(ROOT, "data", "manifest.json")))
SCANS = {e["name"] for e in MAN if e["category"] in ("scene scan", "room-scale scan")}


def bench(method):
    out = {}
    for e in MAN:
        p = os.path.join(ROOT, "benchmark", "results", "reports", f"{e['name']}__{method}.json")
        if os.path.exists(p):
            d = json.load(open(p))
            if "quality" in d:
                out[e["name"]] = d
    return out


def study(it):
    out = {}
    for e in MAN:
        p = os.path.join(ROOT, "benchmark", "study", it, "reports", f"{e['name']}.json")
        if os.path.exists(p):
            d = json.load(open(p))
            if "quality" in d:
                out[e["name"]] = d
    return out


def stats(rs, im):
    if not rs:
        return None
    m = lambda f: st.mean(f(v) for v in rs.values())
    obj = [v for k, v in rs.items() if k not in SCANS]
    both = [k for k in rs if k in im]
    fewer = sum(1 for k in both if rs[k]["topology"]["singularities_per_1k_faces"] < im[k]["topology"]["singularities_per_1k_faces"])
    return dict(n=len(rs), quad=m(lambda v: v["faces"]["quad_ratio"]), sj=m(lambda v: v["quality"]["scaled_jacobian"]["mean"]),
                dist=m(lambda v: v["distance"]["mean_pct"]), cov=m(lambda v: v["features"]["feature_coverage"]),
                cov13=st.mean(v["features"]["feature_coverage"] for v in obj) if obj else float("nan"),
                s1k=m(lambda v: v["topology"]["singularities_per_1k_faces"]), fewer=f"{fewer} / {len(both)}",
                tot=sum(rs[k]["topology"]["singularities"] for k in both),
                tot_im=sum(im[k]["topology"]["singularities"] for k in both),
                minsj=min(v["quality"]["scaled_jacobian"]["mean"] for v in rs.values()),
                minquad=min(v["faces"]["quad_ratio"] for v in rs.values()),
                maxdist=max(v["distance"]["mean_pct"] for v in rs.values()))


def summary_table():
    im = bench("instant_meshes")
    cols = [("**quadremesh** (default)", bench("ours")), ("quadremesh max coverage¹", bench("ours_coverage")),
            ("Instant Meshes", im), ("QuadriFlow", bench("quadriflow")), ("Blender QF", bench("blender_quadriflow"))]
    S = [(n, stats(r, im)) for n, r in cols]
    star = lambda s: "" if s and s["n"] == 15 else "*"
    L = ["| criterion (mean over the models processed) | target | " + " | ".join(n for n, _ in S) + " |",
         "|---|---|" + "---|" * len(S)]
    row = lambda label, tgt, f: L.append(f"| {label} | {tgt} | " + " | ".join(f(s) + (star(s) if s else "") if s else "–" for _, s in S) + " |")
    row("models processed", "–", lambda s: f"{s['n']} / 15")
    row("quad ratio (lowest model)", "≥ 98 %", lambda s: f"{100 * s['quad']:.1f} % ({100 * s['minquad']:.1f} %)")
    row("mean scaled Jacobian (lowest model)", "≥ 0.8", lambda s: f"{s['sj']:.3f} ({s['minsj']:.3f})")
    row("mean distance error (highest model)", "< 0.5 %", lambda s: f"{s['dist']:.3f} % ({s['maxdist']:.3f} %)")
    row("**feature coverage, all 15 models**", "≥ 90 %", lambda s: f"**{100 * s['cov']:.1f} %**")
    row("feature coverage, 13 non-scan models", "≥ 90 %", lambda s: f"{100 * s['cov13']:.1f} %")
    row("singularities / 1k faces", "< IM", lambda s: f"{s['s1k']:.1f}")
    L.append("| fewer singularities than IM, per model | all | " + " | ".join(
        (s["fewer"] if n != "Instant Meshes" else "–") if s else "–" for n, s in S) + " |")
    L.append("| total singularities, models both processed (method / IM) | < IM | " + " | ".join(
        (f"{s['tot']} / {s['tot_im']}" if n != "Instant Meshes" else "–") if s else "–" for n, s in S) + " |")
    L += ["", "\\* over the models that method could process. ¹ `--coverage-mode --path-subdiv 3 --sing-budget-im "
          "--coverage-search` (§6.1). Generated by `docs/gen_tables.py` from `benchmark/results/reports/`."]
    return "\n".join(L)


ITS = [("it0_no_feature_paths", "field constraints + vertex snapping only (start)"),
       ("it1_feature_paths", "+ edge-path recovery (earlier default)"),
       ("it9_trace_all", "+ path recovery over all creases"),
       ("it10_coverage_mode", "+ budgeted loops / refinement / curved splits (`--coverage-mode`)"),
       ("it12_crease_cuts", "it10 + crease cuts (not adopted)"),
       ("it13_feature_density", "it9 + feature-adaptive element size"),
       ("it16_snap_default", "it13 + near-miss snapping"),
       ("it17_default_guarded", "it16 + SJ guard, precise protection (**default**)"),
       ("it18_path_subdiv_sb10", "default + path-edge subdivision, +10 sing./1k"),
       ("it19_path_subdiv_sb25", "default + path-edge subdivision, +25 sing./1k"),
       ("it20_coverage_mode_subdiv", "default + coverage mode + subdivision"),
       ("it21_im_budget", "it20 with the Instant Meshes-referenced budget"),
       ("it22_max_coverage", "it21 + coverage search (**max coverage**)")]


def study_table():
    im = bench("instant_meshes")
    L = ["| iteration | change | coverage (15) | coverage (13 non-scan) | quad | SJ | sing./1k | fewer sing. than IM |",
         "|---|---|---|---|---|---|---|---|"]
    for it, label in ITS:
        rs = study(it)
        s = stats(rs, im)
        if not s:
            continue
        nm = f"{s['n']}" if s["n"] == 15 else f"{s['n']} models"
        L.append(f"| {it.split('_')[0]} | {label} | {s['cov']:.3f}{'' if s['n'] == 15 else ' (' + nm + ')'} | {s['cov13']:.3f} | "
                 f"{s['quad']:.3f} | {s['sj']:.3f} | {s['s1k']:.1f} | {s['fewer']} |")
    s = stats(im, im)
    L.append(f"| – | Instant Meshes | {s['cov']:.3f} | {s['cov13']:.3f} | {s['quad']:.3f} | {s['sj']:.3f} | {s['s1k']:.1f} | – |")
    L += ["", "Generated by `docs/gen_tables.py` from `benchmark/study/`; all iterations and per-model numbers: "
          "[`docs/coverage_study.md`](coverage_study.md)."]
    return "\n".join(L)


def per_model_table():
    ours, cov, im = bench("ours"), bench("ours_coverage"), bench("instant_meshes")
    L = ["| model | category | default | max coverage | Instant Meshes |", "|---|---|---|---|---|"]
    for e in MAN:
        f = lambda r: f"{r[e['name']]['features']['feature_coverage']:.2f}" if e["name"] in r else "–"
        L.append(f"| {e['name']} | {e['category']} | {f(ours)} | {f(cov)} | {f(im)} |")
    return "\n".join(L)


def replace(path, name, text):
    s = open(path).read()
    pat = re.compile(r"(<!-- %s:BEGIN -->\n).*?(\n<!-- %s:END -->)" % (name, name), re.S)
    if not pat.search(s):
        return False
    s = pat.sub(lambda m: m.group(1) + text + m.group(2), s)
    open(path, "w").write(s)
    return True


if __name__ == "__main__":
    tabs = {"SUMMARY": summary_table(), "STUDY": study_table(), "PERMODEL": per_model_table()}
    for doc in ["README.md", "docs/technical_writeup.md"]:
        for k, v in tabs.items():
            if replace(os.path.join(ROOT, doc), k, v):
                print(f"{doc}: {k} updated")
    print(tabs["SUMMARY"])
